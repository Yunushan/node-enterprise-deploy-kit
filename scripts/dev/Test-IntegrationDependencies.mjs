#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const fixture = path.join(root, 'tests/fixtures/nextjs');
const manifest = JSON.parse(fs.readFileSync(path.join(fixture, 'package.json'), 'utf8'));
const lock = JSON.parse(fs.readFileSync(path.join(fixture, 'package-lock.json'), 'utf8'));
const versions = JSON.parse(fs.readFileSync(path.join(root, 'config/nextjs-integration-versions.json'), 'utf8'));
assert.equal(manifest.private, true, 'Integration fixture must remain private.');
assert.equal(lock.lockfileVersion, 3, 'A current npm lockfile is required.');
assert.deepEqual(lock.packages[''].dependencies, manifest.dependencies, 'Manifest and lockfile root dependencies differ.');
for (const [name, version] of Object.entries({ next: versions.next, react: versions.react, 'react-dom': versions.reactDom })) {
  assert.match(version, /^\d+\.\d+\.\d+$/, `${name} must use an exact reviewed version.`);
  assert.equal(manifest.dependencies[name], version, `Update ${name} version config, manifest, and lockfile together.`);
  assert.equal(lock.packages[`node_modules/${name}`].version, version, `${name} lockfile version differs.`);
}
for (const [location, dependency] of Object.entries(lock.packages)) {
  if (!location) continue;
  assert.ok(dependency.integrity?.startsWith('sha512-'), `${location} lacks locked SHA512 integrity.`);
  assert.ok(dependency.resolved?.startsWith('https://registry.npmjs.org/'), `${location} must come from the public TLS npm registry.`);
}
console.log('Integration fixture manifest, exact versions, registry origins, and lockfile integrity OK');

// A pip-compile lock can omit dependencies selected only by another Python
// minor (for example cyclonedx typing_extensions on Python <3.13). Hash-mode
// installation cannot resolve an absent pin, so use the generator's runtime.
const pythonLock = fs.readFileSync(path.join(root, 'scripts/dev/requirements.txt'), 'utf8');
const generatorPython = pythonLock.match(/^# This file is autogenerated by pip-compile with Python (\d+\.\d+)$/m)?.[1];
assert.ok(generatorPython, 'Python tooling lock must identify its generator interpreter.');
const ci = fs.readFileSync(path.join(root, '.github/workflows/ci.yml'), 'utf8');
const pythonRuntimes = [...ci.matchAll(/^\s+python-version:\s*['"]([^'"]+)['"]\s*$/gm)].map(match => match[1]);
assert.ok(pythonRuntimes.length >= 2, 'Dependency audit and quality jobs must select a Python runtime.');
for (const runtime of pythonRuntimes) {
  assert.equal(runtime, generatorPython, 'CI Python must match the hash lock generator; regenerate the lock when changing the interpreter.');
}
console.log(`Python tooling hash lock and CI interpreter agree (${generatorPython})`);
